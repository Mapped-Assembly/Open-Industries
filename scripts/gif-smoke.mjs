async function download(link) {
  const event = page.waitForEvent('download'); await link.click();
  const file = await event;
  const stream = await file.createReadStream();
  const chunks = []; for await (const chunk of stream) chunks.push(chunk);
  return Buffer.concat(chunks);
}
async function verifyGif(link) {
  const bytes = await download(link);
  expect(bytes.subarray(0, 6).toString()).toBe('GIF89a');
  const gif = new GifReader(bytes);
  expect(gif.width).toBe(320); expect(gif.height).toBe(320); expect(gif.numFrames()).toBe(20);
  expect(gif.loopCount()).toBe(0); expect(gif.frameInfo(0).delay).toBe(10);
  const a = Buffer.alloc(320 * 320 * 4); const b = Buffer.alloc(a.length);
  gif.decodeAndBlitFrameRGBA(0, a); gif.decodeAndBlitFrameRGBA(7, b);
  let changed = 0;
  for (let i = 0; i < a.length; i += 4) if (a[i] !== b[i] || a[i + 1] !== b[i + 1] || a[i + 2] !== b[i + 2]) changed++;
  expect(changed).toBeGreaterThan(500);
  expect(new Set(a).size).toBeGreaterThan(20);
  return bytes;
}
